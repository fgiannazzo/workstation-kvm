import Actions
import Foundation
@testable import LocalAPI
import Testing

@Suite("StreamDeckWrappers")
struct StreamDeckWrappersTests {
    private let ctl = "/Applications/Switchboard.app/Contents/MacOS/switchboardctl"

    private func withDirectory<T>(_ body: (URL) throws -> T) throws -> T {
        let directory = FileManager.default.temporaryDirectory.appending(path: "switchboard-sd-\(UUID().uuidString)", directoryHint: .isDirectory)
        defer { try? FileManager.default.removeItem(at: directory) }
        return try body(directory)
    }

    private let registry = ActionRegistry()

    private func read(_ url: URL) throws -> String {
        String(decoding: try Data(contentsOf: url), as: UTF8.self)
    }

    private func mode(_ url: URL) throws -> Int {
        let attributes = try FileManager.default.attributesOfItem(atPath: url.path(percentEncoded: false))
        return try #require((attributes[.posixPermissions] as? NSNumber)?.intValue)
    }

    @Test("one executable .command per macro and per parameter-free action, with the exact script")
    func writesWrappers() throws {
        try withDirectory { directory in
            let urls = try StreamDeckWrappers.generate(
                into: directory,
                macros: MacroStore.defaultMacros,
                actions: registry.descriptors,
                switchboardctlPath: ctl
            )

            let names = urls.map(\.lastPathComponent)
            #expect(names == ["guest.command", "monitor.pbp.off.command", "monitor.pbp.on.command", "monitor.read.command", "solo.command"])
            #expect(urls.allSatisfy { $0.deletingLastPathComponent().standardizedFileURL == directory.standardizedFileURL })

            let guest = try read(directory.appending(path: "guest.command"))
            #expect(guest == """
                #!/bin/bash
                # Generated by `switchboardctl streamdeck export`. Regenerate instead of editing.
                exec "/Applications/Switchboard.app/Contents/MacOS/switchboardctl" run guest

                """)
            let pbp = try read(directory.appending(path: "monitor.pbp.on.command"))
            #expect(pbp.hasPrefix("#!/bin/bash\n"))
            #expect(pbp.hasSuffix(#"exec "\#(ctl)" run monitor.pbp.on"# + "\n"))

            for url in urls {
                #expect(try mode(url) == 0o755, "\(url.lastPathComponent) is executable")
                #expect(FileManager.default.isExecutableFile(atPath: url.path(percentEncoded: false)))
            }
        }
    }

    @Test("actions with parameters get no wrapper")
    func skipsParameterised() throws {
        try withDirectory { directory in
            let urls = try StreamDeckWrappers.generate(into: directory, macros: [], actions: registry.descriptors, switchboardctlPath: ctl)
            let names = Set(urls.map(\.lastPathComponent))
            for action in ["hdmi.select", "hdmi.resync", "usb.select", "delay", "notify"] {
                #expect(!names.contains(action + ".command"), "\(action)")
            }
            #expect(!FileManager.default.fileExists(atPath: directory.appending(path: "usb.select.command").path))
        }
    }

    @Test("a README.txt explains the Open action and lists the wrappers; it is not in the returned list")
    func readme() throws {
        try withDirectory { directory in
            let urls = try StreamDeckWrappers.generate(into: directory, macros: MacroStore.defaultMacros, actions: registry.descriptors, switchboardctlPath: ctl)
            let readme = directory.appending(path: "README.txt")
            let text = try read(readme)
            #expect(text.contains("\"Open\""))
            #expect(text.contains("guest.command"))
            #expect(text.contains("monitor.pbp.on.command"))
            #expect(text.contains("switchboard://run/"))
            #expect(!urls.contains(readme))
            #expect(try mode(readme) == 0o644)
        }
    }

    @Test("running it again changes nothing: same files, same content, no rewrite")
    func idempotent() throws {
        try withDirectory { directory in
            let run = { try StreamDeckWrappers.generate(into: directory, macros: MacroStore.defaultMacros, actions: registry.descriptors, switchboardctlPath: ctl) }
            let first = try run()
            let modified = try first.map { try #require(FileManager.default.attributesOfItem(atPath: $0.path(percentEncoded: false))[.modificationDate] as? Date) }
            let contents = try first.map(read)
            let readme = try read(directory.appending(path: "README.txt"))

            let second = try run()
            #expect(second == first)
            #expect(try second.map(read) == contents)
            #expect(try read(directory.appending(path: "README.txt")) == readme)
            let modifiedAgain = try second.map { try #require(FileManager.default.attributesOfItem(atPath: $0.path(percentEncoded: false))[.modificationDate] as? Date) }
            #expect(modifiedAgain == modified, "a file that is already right is not rewritten")
            #expect(try FileManager.default.contentsOfDirectory(atPath: directory.path).count == first.count + 1)
        }
    }

    @Test("a wrapper that was edited, or lost its execute bit, is put right")
    func repairs() throws {
        try withDirectory { directory in
            let urls = try StreamDeckWrappers.generate(into: directory, macros: MacroStore.defaultMacros, actions: [], switchboardctlPath: ctl)
            let guest = try #require(urls.first { $0.lastPathComponent == "guest.command" })
            let original = try read(guest)

            try Data("#!/bin/bash\necho tampered\n".utf8).write(to: guest)
            try FileManager.default.setAttributes([.posixPermissions: 0o644], ofItemAtPath: guest.path(percentEncoded: false))
            _ = try StreamDeckWrappers.generate(into: directory, macros: MacroStore.defaultMacros, actions: [], switchboardctlPath: ctl)

            #expect(try read(guest) == original)
            #expect(try mode(guest) == 0o755)
        }
    }

    @Test("a new path for switchboardctl rewrites the wrappers; a removed macro's wrapper stays")
    func followsChanges() throws {
        try withDirectory { directory in
            _ = try StreamDeckWrappers.generate(into: directory, macros: MacroStore.defaultMacros, actions: [], switchboardctlPath: "/old/switchboardctl")
            let urls = try StreamDeckWrappers.generate(
                into: directory,
                macros: [MacroStore.defaultMacros[0]],
                actions: [],
                switchboardctlPath: "/new/switchboardctl"
            )
            #expect(urls.map(\.lastPathComponent) == ["guest.command"])
            #expect(try read(directory.appending(path: "guest.command")).contains(#"exec "/new/switchboardctl" run guest"#))
            #expect(FileManager.default.fileExists(atPath: directory.appending(path: "solo.command").path), "nothing is deleted")
        }
    }

    @Test("a macro with the id of an action wins; the action gets no second file")
    func macroShadowsAction() throws {
        try withDirectory { directory in
            let shadow = Macro(id: "monitor.read", name: "Mine", steps: [MacroStep(action: .monitorRead)])
            let urls = try StreamDeckWrappers.generate(into: directory, macros: [shadow], actions: registry.descriptors, switchboardctlPath: ctl)
            #expect(urls.filter { $0.lastPathComponent == "monitor.read.command" }.count == 1)
        }
    }

    @Test("the path is quoted for the shell: spaces are fine, quote, dollar, backtick and backslash are escaped")
    func quoting() {
        #expect(StreamDeckWrappers.script(for: "solo", switchboardctlPath: "/Users/me/My Tools/switchboardctl")
            .hasSuffix(#"exec "/Users/me/My Tools/switchboardctl" run solo"# + "\n"))
        #expect(StreamDeckWrappers.shellQuoted(#"/a"b$c`d\e"#) == #""/a\"b\$c\`d\\e""#)
    }

    @Test("ids that are not safe file names or shell words are refused, writing nothing")
    func unsafeIDs() throws {
        try withDirectory { directory in
            for id in ["../evil", "a b", "x;rm", "", "-flag", "$(id)", "a/b"] {
                let macro = Macro(id: id, name: "Bad", steps: [MacroStep(action: .monitorRead)])
                #expect(throws: StreamDeckWrappersError.unsafeID(id)) {
                    try StreamDeckWrappers.generate(into: directory, macros: [macro], actions: [], switchboardctlPath: ctl)
                }
            }
            #expect(!FileManager.default.fileExists(atPath: directory.path), "validation comes before any write")
        }
    }

    @Test("ids that differ only in case would share a file on a default Mac disk: refused")
    func caseCollision() throws {
        try withDirectory { directory in
            let macros = [
                Macro(id: "Guest", name: "A", steps: [MacroStep(action: .monitorRead)]),
                Macro(id: "guest", name: "B", steps: [MacroStep(action: .monitorRead)]),
            ]
            #expect(throws: StreamDeckWrappersError.collidingFileNames("Guest", "guest")) {
                try StreamDeckWrappers.generate(into: directory, macros: macros, actions: [], switchboardctlPath: ctl)
            }
        }
    }

    @Test("a directory that cannot be created is a writeFailed error")
    func unwritable() throws {
        let blocker = FileManager.default.temporaryDirectory.appending(path: "switchboard-sd-blocker-\(UUID().uuidString)")
        try Data().write(to: blocker)
        defer { try? FileManager.default.removeItem(at: blocker) }
        do {
            _ = try StreamDeckWrappers.generate(into: blocker.appending(path: "inner"), macros: MacroStore.defaultMacros, actions: [], switchboardctlPath: ctl)
            Issue.record("expected an error")
        } catch let error as StreamDeckWrappersError {
            guard case .writeFailed = error else { Issue.record("expected writeFailed, got \(error)"); return }
        }
    }

    @Test("a generated wrapper really runs: it execs the given program with `run <id>`")
    func runsForReal() throws {
        try withDirectory { directory in
            // A stand-in for switchboardctl that records its arguments.
            try FileManager.default.createDirectory(at: directory, withIntermediateDirectories: true)
            let fake = directory.appending(path: "fake ctl")   // a space in the path, on purpose
            let output = directory.appending(path: "args.txt")
            try Data("#!/bin/bash\necho \"$@\" > '\(output.path(percentEncoded: false))'\n".utf8).write(to: fake)
            try FileManager.default.setAttributes([.posixPermissions: 0o755], ofItemAtPath: fake.path(percentEncoded: false))

            let wrappers = directory.appending(path: "wrappers", directoryHint: .isDirectory)
            let urls = try StreamDeckWrappers.generate(into: wrappers, macros: MacroStore.defaultMacros, actions: [], switchboardctlPath: fake.path(percentEncoded: false))
            let solo = try #require(urls.first { $0.lastPathComponent == "solo.command" })

            let process = Process()
            process.executableURL = solo
            try process.run()
            process.waitUntilExit()

            #expect(process.terminationStatus == 0)
            #expect(try read(output) == "run solo\n")
        }
    }
}
