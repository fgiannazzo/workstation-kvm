import Actions
import Foundation

/// What `StreamDeckWrappers.generate` refused to do.
public enum StreamDeckWrappersError: Error, Sendable, Equatable, CustomStringConvertible, LocalizedError {
    /// An id that cannot be a file name or a shell word. `MacroValidator` never lets one into
    /// `macros.json`; this is the check for a caller that builds macros by hand.
    case unsafeID(String)
    /// Two ids that would be the same file on a case-insensitive volume (`Guest` and `guest`).
    case collidingFileNames(String, String)
    case writeFailed(path: String, detail: String)

    public var description: String {
        switch self {
        case .unsafeID(let id):
            return "\"\(id)\" cannot be a wrapper: ids are letters, digits, '.', '-' and '_' and start with a letter or digit"
        case .collidingFileNames(let first, let second):
            return "\"\(first)\" and \"\(second)\" would be the same wrapper file on a case-insensitive disk; rename one"
        case .writeFailed(let path, let detail):
            return "could not write \(path): \(detail)"
        }
    }

    public var errorDescription: String? { description }
}

/// Generated `.command` files, one per macro and one per action that takes no parameters, so a
/// Stream Deck "Open" action can run any of them without the plugin (`docs/STREAMDECK.md`).
///
/// Each file is `#!/bin/bash` and one line, `exec "<switchboardctl>" run <id>`. `switchboardctl run`
/// talks to the app when it is running and does the work itself when it is not, and exits non-zero
/// when the run fails, so Terminal leaves a failed run's window open to be read.
public enum StreamDeckWrappers {
    /// The comment every generated file starts with (after the shebang).
    public static let marker = "# Generated by `switchboardctl streamdeck export`. Regenerate instead of editing."
    public static let readmeName = "README.txt"

    /// Writes the wrappers and `README.txt` into `directory`, creating it if needed, and returns
    /// the wrapper files, sorted by name.
    ///
    /// Safe to run again: a file whose content is already right is not rewritten, and every
    /// wrapper is left executable (0755). Wrappers of macros that no longer exist are not removed.
    ///
    /// - Parameters:
    ///   - macros: one wrapper each, named `<macro id>.command`.
    ///   - actions: one wrapper for each action without parameters, named `<action id>.command`
    ///     (`monitor.pbp.on.command`). An action whose id a macro also uses is skipped: `run`
    ///     resolves that id to the macro, so the macro's wrapper is the one that exists.
    ///   - switchboardctlPath: absolute path of the executable the wrappers call.
    public static func generate(
        into directory: URL,
        macros: [Macro],
        actions: [ActionDescriptor],
        switchboardctlPath: String
    ) throws -> [URL] {
        var ids: [String] = []
        var seen: [String: String] = [:]   // lower-cased id -> id as written
        let parameterFree = actions.filter { $0.parameters.isEmpty }.map { $0.id.rawValue }
        for id in macros.map(\.id) + parameterFree {
            guard MacroValidator.isValidID(id) else { throw StreamDeckWrappersError.unsafeID(id) }
            if let existing = seen[id.lowercased()] {
                if existing == id { continue }
                throw StreamDeckWrappersError.collidingFileNames(existing, id)
            }
            seen[id.lowercased()] = id
            ids.append(id)
        }

        let fileManager = FileManager.default
        do {
            try fileManager.createDirectory(at: directory, withIntermediateDirectories: true)
        } catch {
            throw StreamDeckWrappersError.writeFailed(path: directory.path(percentEncoded: false), detail: error.localizedDescription)
        }

        var written: [URL] = []
        for id in ids.sorted() {
            let url = directory.appending(path: id + ".command", directoryHint: .notDirectory)
            try write(script(for: id, switchboardctlPath: switchboardctlPath), to: url, mode: 0o755)
            written.append(url)
        }
        try write(
            readme(wrappers: ids.sorted(), macros: macros.map(\.id)),
            to: directory.appending(path: readmeName, directoryHint: .notDirectory),
            mode: 0o644
        )
        return written
    }

    /// The text of one wrapper.
    public static func script(for id: String, switchboardctlPath: String) -> String {
        """
        #!/bin/bash
        \(marker)
        exec \(shellQuoted(switchboardctlPath)) run \(id)

        """
    }

    /// Double quotes, with the four characters that are special inside them escaped.
    static func shellQuoted(_ text: String) -> String {
        var quoted = "\""
        for character in text {
            if "\\\"$`".contains(character) { quoted.append("\\") }
            quoted.append(character)
        }
        return quoted + "\""
    }

    static func readme(wrappers: [String], macros: [String]) -> String {
        let macroSet = Set(macros)
        let macroLines = wrappers.filter { macroSet.contains($0) }.map { "    \($0).command" }
        let actionLines = wrappers.filter { !macroSet.contains($0) }.map { "    \($0).command" }
        return """
        Switchboard wrappers for the Stream Deck "Open" action
        =======================================================

        Generated by `switchboardctl streamdeck export`. Each .command file runs one macro or one
        action that needs no parameters, by calling `switchboardctl run <id>`.

        Macros:
        \(macroLines.isEmpty ? "    (none)" : macroLines.joined(separator: "\n"))

        Actions:
        \(actionLines.isEmpty ? "    (none)" : actionLines.joined(separator: "\n"))

        Put one on a key
        ----------------
        1. In the Stream Deck app, drag the "Open" action (System category) onto a key.
        2. Choose the .command file in its file field (or drag the file from Finder onto it).
        3. Press the key. macOS opens the file with Terminal, which runs it: the run is printed and
           the shell exits. If Terminal leaves the window open after a successful run, set
           Terminal > Settings > Profiles > Shell > "When the shell exits" to "Close if the shell
           exited cleanly". A failed run exits non-zero, so its window stays open to be read.

        Notes
        -----
        - The files call `switchboardctl` by its absolute path. If you move or reinstall it, run
          `switchboardctl streamdeck export` again; it is safe to repeat and rewrites only what
          changed.
        - Export again after you add or rename a macro. A wrapper of a macro you deleted is not
          removed: delete it yourself.
        - `switchboardctl run` uses the Switchboard app when it is running (one run at a time, and
          the app's menu bar shows the result) and works by itself when it is not. To talk to the
          app it reads the API token from the login keychain; the first time, macOS asks whether
          switchboardctl may use it: choose Always Allow. (After you rebuild or replace
          switchboardctl it asks again.)
        - With the app installed, a key needs no wrapper: the "Website" action (System category)
          with the URL switchboard://run/<id> runs it through the app. The "Open" action does not
          take that URL (Stream Deck 7.6 reports "failed to execute"). See docs/STREAMDECK.md in
          the Switchboard repository.

        """
    }

    // MARK: Writing

    /// Writes `text` unless the file already has exactly that content, then sets the mode.
    private static func write(_ text: String, to url: URL, mode: Int) throws {
        let path = url.path(percentEncoded: false)
        let fileManager = FileManager.default
        do {
            let data = Data(text.utf8)
            if (try? Data(contentsOf: url)) != data {
                try data.write(to: url, options: .atomic)
            }
            let current = (try fileManager.attributesOfItem(atPath: path)[.posixPermissions] as? NSNumber)?.intValue
            if current != mode {
                try fileManager.setAttributes([.posixPermissions: mode], ofItemAtPath: path)
            }
        } catch {
            throw StreamDeckWrappersError.writeFailed(path: path, detail: error.localizedDescription)
        }
    }
}
